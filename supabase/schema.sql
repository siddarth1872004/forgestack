-- ForgeStock schema for Supabase PostgreSQL.
-- Keep the database private; the app connects through DATABASE_URL from the server.
create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username varchar(80) not null unique,
  password_hash varchar(255) not null,
  role varchar(30) not null default 'admin',
  is_active boolean not null default true
);
create table if not exists public.raw_material_categories (
  id bigint generated by default as identity primary key,
  name varchar(80) not null unique
);
create table if not exists public.suppliers (
  id bigint generated by default as identity primary key,
  name varchar(120) not null,
  contact varchar(120),
  email varchar(120)
);
create table if not exists public.raw_materials (
  id bigint generated by default as identity primary key,
  material_code varchar(30) not null unique,
  name varchar(120) not null,
  unit varchar(20) not null,
  quantity numeric(12,2) not null default 0,
  min_stock numeric(12,2) not null default 0,
  category_id bigint not null references public.raw_material_categories(id),
  supplier_id bigint references public.suppliers(id)
);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  product_code varchar(30) not null unique,
  name varchar(120) not null,
  unit varchar(20) not null default 'units',
  quantity numeric(12,2) not null default 0,
  min_stock numeric(12,2) not null default 0
);
create table if not exists public.production_orders (
  id bigint generated by default as identity primary key,
  order_code varchar(30) not null unique,
  product_id bigint not null references public.products(id),
  quantity numeric(12,2) not null,
  status varchar(30) not null default 'Pending',
  created_at timestamp not null default now(),
  started_at timestamp,
  completed_at timestamp
);
create table if not exists public.material_consumptions (
  id bigint generated by default as identity primary key,
  production_order_id bigint not null references public.production_orders(id),
  material_id bigint not null references public.raw_materials(id),
  quantity numeric(12,2) not null,
  consumed_at timestamp not null default now()
);
create table if not exists public.inventory_transactions (
  id bigint generated by default as identity primary key,
  item_type varchar(30) not null,
  item_id bigint not null,
  item_name varchar(120) not null,
  transaction_type varchar(30) not null,
  quantity numeric(12,2) not null,
  reference varchar(50),
  note text,
  created_at timestamp not null default now()
);
create index if not exists ix_users_username on public.users(username);
create index if not exists ix_raw_materials_material_code on public.raw_materials(material_code);
create index if not exists ix_raw_materials_name on public.raw_materials(name);
create index if not exists ix_products_product_code on public.products(product_code);
create index if not exists ix_products_name on public.products(name);
create index if not exists ix_production_orders_order_code on public.production_orders(order_code);
create index if not exists ix_production_orders_status on public.production_orders(status);
create index if not exists ix_inventory_transactions_created_at on public.inventory_transactions(created_at);
